# درس ۹: دیکشنری، تاپل و انتخاب‌ها
# مثال ۵: دیکشنری تو در تو و لیست دیکشنری

students = [
    {'نام': 'علی', 'نمره': 17},
    {'نام': 'سارا', 'نمره': 20},
    {'نام': 'رضا', 'نمره': 14},
]
for s in students:
    print(s['نام'], s['نمره'])

best = max(students, key=lambda s: s['نمره'])
print('بهترین:', best['نام'])
